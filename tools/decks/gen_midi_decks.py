"""Generate the committed `midi_*` decks — the IEEE123-CLASS synthetic network
that carries the asymmetric-configuration and control/protection/metering
coverage of the micro gates (tests/corpus/asymmetric/, tests/corpus/controls/)
at a scale where LARGE-network failure modes exist. Micro decks cannot exercise
them; the vendored IEEE123/8500 corpus runs exercise the scale but not the
asymmetric element configs or the element-state channels. The midi network has:

  - >100 nodes (multi-digit node ordering, non-trivial sparse fill/ordering);
  - a 14-segment radial backbone (deep-chain voltage-drop accumulation);
  - a LOOP (two lateral ends tied) + a PARALLEL backbone segment (duplicate
    Y-stamp density — the insertion-order summation class);
  - 3 voltage levels (115 / 12.47 / 4.16+0.48) through cascaded transformers;
  - mixed 3ph/2ph/1ph laterals (the IEEE123 hallmark);
  - the asymmetric configs from the micro gates: Z1≠Z2 source + series
    reactor, FULL-asymmetric-input line/cap matrices, per-phase-unequal
    1-phase-bank taps, delta tertiary (with the proven physical common-mode pin);
  - (controls variant) cascaded regulators — LTC + a 3×1-phase bank — plus
    CapControls, InvControl, StorageController, meter/monitors: many controls
    acting in the same control iterations (queue tie-break ordering);
  - (protection variant) substation relay -> midline recloser -> lateral fuse
    coordination with the fault at the END of the deep lateral.

Deterministic (no randomness, no timestamps): rerunning reproduces the decks
byte-for-byte. The generated decks are COMMITTED artifacts; regenerate only
deliberately:

    python tools/decks/gen_midi_decks.py
"""

