N_BACKBONE = 14  # segments bb1..bb15 (bb8->bb9 is the Z1<>Z2 series reactor)
REACTOR_SEG = 8  # bb8 -> bb9


def backbone(fixed_taps: bool) -> list[str]:
    """Substation + the 14-segment backbone with the mid-feeder 1-phase reg bank."""
    out = [
        "! Substation: Dy 115/12.47 (the LTC in the controls variant).",
        "new transformer.sub phases=3 windings=2 buses=(src, bb1) conns=(delta, wye)",
        "~ kvs=(115, 12.47) kvas=(20000, 20000) xhl=7"
        + (" taps=[1.0 1.0125]" if fixed_taps else ""),
    ]
    for i in range(1, N_BACKBONE + 1):
        a, b = f"bb{i}", f"bb{i + 1}"
        if i == REACTOR_SEG:
            out += [
                f"! Backbone segment {i}: the Z1<>Z2 series reactor (the",
                "! non-reciprocal-YPrim class of the 03c63f2 stamp bug) mid-chain.",
                f"new reactor.rser phases=3 bus1={a} bus2={b}",
                "~ Z1=[0.35 0.62] Z2=[0.08 0.21] Z0=[0.5 0.9]",
            ]
            continue
        code = "lcc" if i % 5 == 0 else "lca"
        length = [2, 3, 2, 4, 3, 2, 3, 0, 4, 2, 3, 2, 3, 2][i - 1]
        out.append(
            f"new line.bb{i}_{i + 1} bus1={a} bus2={b} linecode={code} "
            f"length={length} units=kft"
        )
    out += [
        "! Parallel line on segment 5 (duplicate stamps on the same node pair).",
        "new line.bb5_6p bus1=bb5 bus2=bb6 linecode=lcc length=4 units=kft",
        "",
        "! Mid-feeder 1-phase regulating bank bb10 -> rb (per-phase-unequal",
        "! FIXED taps in the asym variant; RegControls in the controls variant).",
    ]
    bank_taps = ["1.025", "0.9875", "1.05"] if fixed_taps else ["1.0", "1.0", "1.0"]
    for ph, tap in zip((1, 2, 3), bank_taps):
        out += [
            f"new transformer.rbank{ph} phases=1 windings=2 "
            f"buses=(bb10.{ph}, rb.{ph}) conns=(wye, wye)",
            f"~ kvs=(7.2, 7.2) kvas=(2500, 2500) xhl=1 taps=[1.0 {tap}]",
        ]
    out += [
        "! The backbone continues from the regulated bus.",
        "new line.rb_bb11 bus1=rb bus2=bb11 linecode=lca length=2 units=kft",
    ]
    return out


